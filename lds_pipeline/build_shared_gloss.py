def ollama_up() -> bool:
    try:
        req = urllib.request.Request(OLLAMA_TAGS, method="GET")
        with urllib.request.urlopen(req, timeout=3) as resp:
            data = json.loads(resp.read())
        return bool(data.get("models") is not None)
    except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError):
        return False


def installed_models() -> list[str]:
    """Read manifests dir; fallback to /api/tags if server is up."""
    mdir = Path.home() / ".ollama" / "models" / "manifests" / "registry.ollama.ai" / "library"
    names: list[str] = []
    if mdir.exists():
        for family in sorted(mdir.iterdir()):
            if family.is_dir():
                for tag in sorted(family.iterdir()):
                    if tag.is_file():
                        names.append(f"{family.name}:{tag.name}")
    if not names and ollama_up():
        try:
            with urllib.request.urlopen(OLLAMA_TAGS, timeout=3) as resp:
                data = json.loads(resp.read())
            names = [m.get("name", "") for m in data.get("models", []) if m.get("name")]
        except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError):
            pass
    return names


def pick_model(requested: str | None) -> str | None:
    have = set(installed_models())
    if requested and requested in have:
        return requested
    for cand in MODEL_PREFERENCE:
        if cand in have:
            return cand
    return None


