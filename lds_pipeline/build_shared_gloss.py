def ollama_generate(model: str, system: str, user: str) -> str:
    payload = json.dumps({
        "model": model,
        "prompt": f"{system}\n\n{user}",
        "stream": False,
        "options": {
            "temperature": TEMPERATURE,
            "num_thread": NUM_THREAD,
            "num_ctx": NUM_CTX,
            "num_predict": NUM_PREDICT,
        },
    }).encode()
    req = urllib.request.Request(
        OLLAMA_URL, data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=OLLAMA_TIMEOUT_S) as resp:
        data = json.loads(resp.read())
    return (data.get("response") or "").strip()


def _repair_prompt(reason: str) -> str:
    return (
        f"Your previous response was rejected ({reason}). "
        "Return ONE JSON object fenced in ```json ...``` with ALL required keys: "
        "term, language, root, literal_sense, semantic_range, first_appearance, "
        "major_scriptural_pattern, symbolic_structure, numerical_letter_observations, "
        "messianic_fulfillment, reveals_about_christ, confidence_by_claim, final_synthesis. "
        "All values plain English ASCII prose (transliterations only, no Hebrew/Greek script). "
        "confidence_by_claim is an object whose values are one of: lexical, pattern, inference, speculation. "
        "Do not apologize, do not preface — just the JSON block."
    )


def generate_entry(model: str, rec: dict[str, Any]) -> tuple[dict[str, Any] | None, str]:
    bundle = _morph_bundle(rec)
    examples = _pick_examples(rec, n=3)
    dona = _donaldson_hint(rec)
    user = _build_user_prompt(rec, bundle, examples, dona)
    try:
        raw = ollama_generate(model, DEFINE_SYSTEM, user)
    except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as e:
        return None, f"ollama-error:{type(e).__name__}"
    obj = _extract_json(raw)
    if obj is None:
        repair_user = user + "\n\n" + _repair_prompt("could not parse JSON from the response")
        try:
            raw2 = ollama_generate(model, DEFINE_SYSTEM, repair_user)
        except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as e:
            return None, f"ollama-error-retry:{type(e).__name__}"
        obj = _extract_json(raw2)
        if obj is None:
            return None, "json-parse-failed"
    entry, reason = _validate(obj)
    if entry is None:
        repair_user = user + "\n\n" + _repair_prompt(reason)
        try:
            raw3 = ollama_generate(model, DEFINE_SYSTEM, repair_user)
        except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as e:
            return None, f"ollama-error-retry:{type(e).__name__}"
        obj2 = _extract_json(raw3)
        if obj2 is None:
            return None, "json-parse-failed-retry"
        entry, reason = _validate(obj2)
        if entry is None:
            return None, f"validation-failed:{reason}"
    # Augment with grounding facts so the reader can show chips even if the model omitted them.
    entry["_facts"] = {
        "stem": rec["stem"],
        "surface": _display_form(rec),
        "lang": bundle.get("lang") or "",
        "lemma": bundle.get("lemma") or "",
        "surface_gr": bundle.get("surface_gr") or "",
        "surface_he": bundle.get("surface_he") or "",
        "morph": bundle.get("morph") or "",
        "count": rec.get("count", 0),
        "first_appearance_ref": _first_appearance_label(rec),
    }
    return entry, ""


