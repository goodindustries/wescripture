# Fact assembly
# -----------------------------------------------------------------------------
def _dominant_volume(rec: dict[str, Any]) -> str:
    vols = rec.get("volumes") or {}
    if not vols:
        return "other"
    # Prefer ot/nt/bofm where the stem actually lives.
    return max(vols.items(), key=lambda kv: kv[1])[0]


def _display_form(rec: dict[str, Any]) -> str:
    forms = rec.get("forms") or {}
    if not forms:
        return rec["stem"].capitalize()
    best = max(forms.items(), key=lambda kv: kv[1])[0]
    return best[:1].upper() + best[1:] if len(best) > 1 else best.upper()


def _pick_examples(rec: dict[str, Any], n: int = 3) -> list[dict[str, str]]:
    """Prefer spread across volumes; truncate each."""
    pool = rec.get("examples") or []
    seen_vol: set[str] = set()
    picked: list[dict[str, str]] = []
    for ex in pool:
        vol = morph.slug_volume(ex.get("slug", ""))
        if vol in seen_vol:
            continue
        picked.append(ex)
        seen_vol.add(vol)
        if len(picked) >= n:
            break
    if len(picked) < n:
        for ex in pool:
            if ex not in picked:
                picked.append(ex)
            if len(picked) >= n:
                break
    out = []
    for ex in picked[:n]:
        t = re.sub(r"\s+", " ", ex.get("text") or "")[:280].strip()
        if t and ex.get("ref"):
            out.append({"ref": ex["ref"], "text": t})
    return out


def _first_appearance_label(rec: dict[str, Any]) -> str:
    slug = rec.get("first_slug") or ""
    v = rec.get("first_v") or 0
    if not slug:
        return ""
    book = morph.book_title_from_slug(slug)
    ch = rec.get("first_ch") or 0
    return f"{book} {ch}:{v}" if ch else book


def _donaldson_hint(rec: dict[str, Any]) -> str:
    """If Donaldson has a word-study row whose headword matches this stem, return the plain/meaning text."""
    slug = rec.get("first_slug") or ""
    v = rec.get("first_v") or 0
    if not slug or not v:
        return ""
    path = DONALDSON / f"{slug}.json"
    if not path.exists():
        return ""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return ""
    block = data.get(str(v)) or {}
    forms = {f.lower() for f in (rec.get("forms") or {})}
    forms.add(rec["stem"].lower())
    best = ""
    for w in (block.get("words") or []):
        lab = (w.get("word") or "").strip().lower()
        if not lab:
            continue
        if any(lab.startswith(f) or f.startswith(lab) for f in forms):
            note = (w.get("plain") or w.get("meaning") or "").strip()
            if note and len(note) > len(best):
                best = note
    return re.sub(r"\s+", " ", best)[:600]


def _morph_bundle(rec: dict[str, Any]) -> dict[str, Any]:
    """Try to align the stem to an original-language lemma via its first appearance."""
    slug = rec.get("first_slug") or ""
    ch = rec.get("first_ch") or 0
    v = rec.get("first_v") or 0
    vol = _dominant_volume(rec)
    surface = _display_form(rec)
    nt_toks: list[dict[str, Any]] = []
    ot_toks: list[dict[str, Any]] = []
    try:
        if vol == "nt":
            nt_toks = morph.nt_tokens_for_verse(morph.book_title_from_slug(slug), ch, v)
        elif vol == "ot":
            ot_toks = morph.ot_tokens_for_verse(slug, ch, v)
    except Exception:  # morphology data may be missing
        pass
    bundle = None
    try:
        bundle = morph.align_stem(vol, rec["stem"], surface, nt_toks, ot_toks)
    except Exception:
        bundle = None
    if bundle is None:
        bundle = morph.english_only_bundle(vol, rec["stem"], surface)
    return bundle


