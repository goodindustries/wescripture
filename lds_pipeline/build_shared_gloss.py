def watchdog_check() -> None:
    try:
        import psutil  # type: ignore
    except ImportError:
        return
    try:
        proc = psutil.Process(os.getpid())
        rss_gb = proc.memory_info().rss / (1024 ** 3)
        load1 = os.getloadavg()[0]
        if rss_gb > WATCHDOG_RSS_GB or load1 > (os.cpu_count() or 4) * 0.5:
            log(f"watchdog: rss={rss_gb:.1f}gb load1={load1:.1f} — sleeping {WATCHDOG_SLEEP_S}s")
            time.sleep(WATCHDOG_SLEEP_S)
    except Exception:
        pass


