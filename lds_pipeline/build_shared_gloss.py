def shard_key_for(stem: str) -> str:
    s = (stem or "").lower()
    if not s:
        return "_other"
    c = s[0]
    if c.isalpha():
        return c
    if c.isdigit():
        return "_digits"
    return "_other"


def shard_path(key: str) -> Path:
    return GLOSS_DIR / f"en.{key}.json"


def load_shard(key: str) -> dict[str, Any]:
    p = shard_path(key)
    if not p.exists():
        return {"_meta": {"prompt_version": PROMPT_VERSION, "shard": key}, "stems": {}}
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"_meta": {"prompt_version": PROMPT_VERSION, "shard": key}, "stems": {}}
    data.setdefault("_meta", {"prompt_version": PROMPT_VERSION, "shard": key})
    data.setdefault("stems", {})
    return data


def write_shard_atomic(key: str, data: dict[str, Any]) -> None:
    GLOSS_DIR.mkdir(parents=True, exist_ok=True)
    p = shard_path(key)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=0), encoding="utf-8")
    tmp.replace(p)


def rebuild_index() -> None:
    GLOSS_DIR.mkdir(parents=True, exist_ok=True)
    index = {"_meta": {"prompt_version": PROMPT_VERSION, "generated": datetime.now(timezone.utc).isoformat(timespec="seconds")},
             "byStem": {}, "byHead": {}}
    for p in sorted(GLOSS_DIR.glob("en.*.json")):
        if p.name == "en.index.json":
            continue
        key = p.stem[len("en."):]
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        for stem, entry in (data.get("stems") or {}).items():
            index["byStem"][stem] = key
            head = (entry.get("term") or "").strip().lower()
            if head:
                index["byHead"].setdefault(head, stem)
            facts = entry.get("_facts") or {}
            surf = (facts.get("surface") or "").strip().lower()
            if surf:
                index["byHead"].setdefault(surf, stem)
    (GLOSS_DIR / "en.index.json").write_text(
        json.dumps(index, ensure_ascii=False, indent=0), encoding="utf-8"
    )


