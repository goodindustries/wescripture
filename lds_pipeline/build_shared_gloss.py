# Main runner
# -----------------------------------------------------------------------------
_STOP = {"flag": False}


def _install_signals() -> None:
    def _handler(signum, frame):  # noqa: ARG001
        _STOP["flag"] = True
        log(f"signal {signum} — finishing current stem, then stopping")
    for s in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(s, _handler)
        except (ValueError, OSError):
            pass


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model", help="Ollama model tag; auto-detect if absent")
    ap.add_argument("--limit", type=int, default=0, help="Process at most N stems (priority order)")
    ap.add_argument("--smoke", action="store_true", help="Alias for --limit 10")
    ap.add_argument("--stems", nargs="*", help="Explicit stems to process (skips priority ordering)")
    ap.add_argument("--force", action="store_true", help="Rebuild even if already in shard")
    ap.add_argument("--skip-watchdog", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="Print work plan; no Ollama calls")
    args = ap.parse_args()

    _install_signals()

    if not ollama_up():
        log("ollama not reachable at 127.0.0.1:11434. Start with: ollama serve &")
        return 2

    model = pick_model(args.model)
    if not model:
        log("no suitable model installed. Want one of: " + ", ".join(MODEL_PREFERENCE))
        return 2
    log(f"model: {model}")

    os.environ.setdefault("OLLAMA_NUM_PARALLEL", "1")
    os.environ.setdefault("OLLAMA_MAX_LOADED_MODELS", "1")

    universe = gather_stem_universe()
    log(f"universe: {len(universe)} candidate stems after stopword filtering")

    if args.stems:
        wanted = {s.lower() for s in args.stems}
        work = [r for r in universe if r["stem"].lower() in wanted]
    else:
        work = list(universe)

    limit = 10 if args.smoke else args.limit
    if limit and limit > 0:
        work = work[:limit]

    if args.dry_run:
        for rec in work[:25]:
            log(f"  plan: {rec['stem']:20s} count={rec['count']:4d} first={_first_appearance_label(rec)}")
        log(f"dry-run: {len(work)} stems would be processed")
        return 0

    # Load existing shards lazily; keep in-memory working copies.
    shards: dict[str, dict[str, Any]] = {}

    def _shard(key: str) -> dict[str, Any]:
        if key not in shards:
            shards[key] = load_shard(key)
        return shards[key]

    done = 0
    skipped = 0
    failed = 0
    dirty_keys: set[str] = set()
    FLUSH_EVERY = 5

    start = time.time()
    for i, rec in enumerate(work):
        if _STOP["flag"]:
            break
        stem = rec["stem"]
        key = shard_key_for(stem)
        sh = _shard(key)
        if (not args.force) and stem in sh["stems"]:
            skipped += 1
            continue
        if not args.skip_watchdog and i > 0 and i % WATCHDOG_EVERY == 0:
            watchdog_check()

        t0 = time.time()
        entry, reason = generate_entry(model, rec)
        elapsed = time.time() - t0
        if entry is None:
            failed += 1
            log(f"  fail {stem:20s} reason={reason} ({elapsed:.1f}s)")
        else:
            sh["stems"][stem] = entry
            sh["_meta"]["model"] = model
            sh["_meta"]["prompt_version"] = PROMPT_VERSION
            sh["_meta"]["updated"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
            dirty_keys.add(key)
            done += 1
            log(f"  ok   {stem:20s} count={rec['count']:4d} first={_first_appearance_label(rec)} ({elapsed:.1f}s)")

        if dirty_keys and (done % FLUSH_EVERY == 0 or _STOP["flag"]):
            for k in list(dirty_keys):
                write_shard_atomic(k, shards[k])
            dirty_keys.clear()
            rebuild_index()

        # Jitter to avoid back-to-back generations with no gap.
        time.sleep(random.uniform(JITTER_MIN_S, JITTER_MAX_S))

    # Final flush.
    if dirty_keys:
        for k in list(dirty_keys):
            write_shard_atomic(k, shards[k])
        rebuild_index()
    else:
        # Still refresh the index so additions (e.g. via --stems) are discoverable.
        rebuild_index()

    wall = time.time() - start
    log(f"done: wrote={done} skipped={skipped} failed={failed} wall={wall:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
