DEFINE_SYSTEM = (
    "You perform a deep scriptural-etymological analysis, not a quick definition. "
    "Begin with the original Hebrew or Greek term, transliteration, root letters, morphology, "
    "literal meaning, and semantic range. Trace the first appearance in scripture and why it matters. "
    "Trace major uses across covenant, priesthood, kingship, temple, sacrifice, creation, exodus, "
    "inheritance, judgment, exile, redemption, resurrection, and Zion contexts. Note embedded structures: "
    "repeated phrases, root echoes, paired terms, covenant patterns, symbolic oppositions, and numerical "
    "or letter patterns. Distinguish lexical certainty, strong textual pattern, plausible symbolic "
    "inference, and speculation. Do not force connections. Prefer primary texts and repeated scriptural "
    "architecture over later commentary. Close by showing what the word reveals about the wisdom, "
    "character, mission, or pattern of Jesus Christ. "
    "Respond with ONE JSON object, fenced in a ```json block, containing exactly these keys: "
    "term, language, root, literal_sense, semantic_range, first_appearance, major_scriptural_pattern, "
    "symbolic_structure, numerical_letter_observations, messianic_fulfillment, reveals_about_christ, "
    "confidence_by_claim, final_synthesis. "
    "All string values must be plain English ASCII (no Hebrew/Greek script; transliterations only). "
    "confidence_by_claim is an object mapping short claim labels to one of: "
    "'lexical', 'pattern', 'inference', 'speculation'. "
    "Write complete prose paragraphs in each field. No bullet lists. No filler."
)

REQUIRED_KEYS = {
    "term", "language", "root", "literal_sense", "semantic_range",
    "first_appearance", "major_scriptural_pattern", "symbolic_structure",
    "numerical_letter_observations", "messianic_fulfillment", "reveals_about_christ",
    "confidence_by_claim", "final_synthesis",
}
CONF_VALUES = {"lexical", "pattern", "inference", "speculation"}


def _build_user_prompt(rec: dict[str, Any], bundle: dict[str, Any],
                       examples: list[dict[str, str]], dona_hint: str) -> str:
    first = _first_appearance_label(rec)
    lang_label = {
        "grc": "Greek (New Testament)",
        "hbo": "Hebrew (Old Testament)",
        "eng": "English (Restoration volume / no original-language alignment)",
    }.get(bundle.get("lang", ""), "English")
    volumes = rec.get("volumes") or {}
    vol_label = ", ".join(f"{k}:{v}" for k, v in sorted(volumes.items(), key=lambda kv: -kv[1]))
    lines = [
        "Facts (do not invent beyond these; use them to ground the analysis):",
        f"- English stem: {rec['stem']}",
        f"- Representative surface form in the text: {_display_form(rec)}",
        f"- Language class: {lang_label}",
        f"- Lemma (if aligned): {bundle.get('lemma') or '(none)'}",
        f"- Greek surface (if any): {bundle.get('surface_gr') or ''}",
        f"- Hebrew surface (if any): {bundle.get('surface_he') or ''}",
        f"- Morphology tag (if any): {bundle.get('morph') or ''}",
        f"- Alignment confidence: {bundle.get('confidence') or 'none'}",
        f"- Appearance count across canon: {rec.get('count', 0)} verses",
        f"- Volume distribution (most to least): {vol_label}",
        f"- Earliest canonical appearance: {first or '(unknown)'}",
    ]
    if dona_hint:
        lines += ["- Donaldson word-study note (paraphrase; do not quote):", f"  * {dona_hint}"]
    if examples:
        lines.append("- Representative scripture excerpts:")
        for ex in examples:
            lines.append(f"  * {ex['ref']}: {ex['text']}")
    lines.append(
        "Return the JSON object now. Write full paragraphs in every field. "
        "If something is genuinely unknown, say so plainly in that field and mark the "
        "relevant claim as 'speculation' in confidence_by_claim."
    )
    return "\n".join(lines)


_FENCE_JSON_RE = re.compile(r"```(?:json)?\s*(\{.*?\})\s*```", re.DOTALL | re.IGNORECASE)
_THINK_RE = re.compile(r"<think>.*?</think>", re.DOTALL | re.IGNORECASE)


def _extract_json(text: str) -> dict[str, Any] | None:
    if not text:
        return None
    text = _THINK_RE.sub("", text).strip()
    m = _FENCE_JSON_RE.search(text)
    raw = m.group(1) if m else None
    if raw is None:
        # Best-effort: take the largest balanced {...} block.
        depth = 0
        start = -1
        best = None
        for i, c in enumerate(text):
            if c == "{":
                if depth == 0:
                    start = i
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0 and start >= 0:
                    cand = text[start:i + 1]
                    if best is None or len(cand) > len(best):
                        best = cand
        raw = best
    if not raw:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        # Remove trailing commas as a last resort.
        cleaned = re.sub(r",(\s*[}\]])", r"\1", raw)
        try:
            return json.loads(cleaned)
        except json.JSONDecodeError:
            return None


def _ascii_only(s: str) -> str:
    t = (s or "").replace("\u2026", "...").replace("\u2013", "-").replace("\u2014", "-")
    t = t.replace("\u201c", '"').replace("\u201d", '"').replace("\u2018", "'").replace("\u2019", "'")
    t = unicodedata.normalize("NFKD", t)
    return t.encode("ascii", "ignore").decode("ascii")


def _normalize_entry(obj: dict[str, Any]) -> dict[str, Any] | None:
    if not isinstance(obj, dict):
        return None
    missing = REQUIRED_KEYS - set(obj.keys())
    if missing:
        return None
    out: dict[str, Any] = {}
    for k in REQUIRED_KEYS:
        v = obj[k]
        if k == "confidence_by_claim":
            if not isinstance(v, dict) or not v:
                return None
            conf: dict[str, str] = {}
            for ck, cv in v.items():
                label = _ascii_only(str(ck)).strip()[:60]
                val = _ascii_only(str(cv)).strip().lower()
                if val not in CONF_VALUES:
                    # Map common stand-ins.
                    if val in {"certain", "strong"}:
                        val = "lexical"
                    elif val in {"likely", "probable"}:
                        val = "pattern"
                    elif val in {"possible", "suggestive"}:
                        val = "inference"
                    else:
                        val = "speculation"
                if label:
                    conf[label] = val
            if not conf:
                return None
            out[k] = conf
        else:
            s = _ascii_only(str(v)).strip()
            if not s or len(s) < 3:
                return None
            out[k] = s
    return out


def _validate(obj: dict[str, Any]) -> tuple[dict[str, Any] | None, str]:
    entry = _normalize_entry(obj)
    if entry is None:
        return None, "missing-keys-or-empty-values"
    # Quality floor: the analytical fields should have some real prose.
    for field in ("literal_sense", "semantic_range", "major_scriptural_pattern",
                  "reveals_about_christ", "final_synthesis"):
        if len(entry[field]) < 40:
            return None, f"field-too-short:{field}"
    return entry, ""


