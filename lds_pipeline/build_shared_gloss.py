def canon_chapter_order() -> list[str]:
    """Return chapter slugs in canonical order from toc.json."""
    try:
        toc = json.loads(TOC_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return sorted(p.stem for p in CHAPTERS.glob("*.html") if p.stem != "index")
    order: list[str] = []
    for item in toc:
        if not isinstance(item, dict):
            continue
        if item.get("type") == "chapter" and item.get("id"):
            order.append(item["id"])
    if not order:
        order = sorted(p.stem for p in CHAPTERS.glob("*.html") if p.stem != "index")
    return order


def load_words(path: Path) -> dict[str, Any]:
    try:
        root = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if isinstance(root, dict) and "_m" in root and "v" in root:
        catalog = root.get("_m") or []
        verses_raw = root.get("v") or {}
        out: dict[str, Any] = {}
        for vk, vdata in verses_raw.items():
            inner: dict[str, Any] = {}
            for stem, entry in (vdata or {}).items():
                e = dict(entry)
                if "matches" not in e and e.get("m"):
                    e["matches"] = [catalog[i] for i in e["m"] if 0 <= i < len(catalog)]
                inner[stem] = e
            out[vk] = inner
        return out
    return root


def is_stopword(stem: str) -> bool:
    s = (stem or "").lower()
    if not s or len(s) < 2:
        return True
    if s in STOPS or s in GRAPH_STOPS:
        return True
    # Pure numerics / short tokens are not useful headwords.
    if s.isdigit():
        return True
    return False


def gather_stem_universe() -> list[dict[str, Any]]:
    """
    Walk chapter _words.json files in canonical order, aggregate per-stem info.

    Returns a list of stem records sorted by descending appearance count so
    highest-impact stems are processed first.
    """
    order = canon_chapter_order()
    order_set = set(order)
    for p in CHAPTERS.glob("*_words.json"):
        stem_id = p.stem[: -len("_words")]
        if stem_id not in order_set:
            order.append(stem_id)

    records: dict[str, dict[str, Any]] = {}
    for slug in order:
        wpath = CHAPTERS / f"{slug}_words.json"
        if not wpath.exists():
            continue
        words = load_words(wpath)
        if not isinstance(words, dict):
            continue
        try:
            ch_num = int(slug.rsplit("_", 1)[-1])
        except ValueError:
            ch_num = 0
        for vk, vdata in words.items():
            if not str(vk).isdigit() or not isinstance(vdata, dict):
                continue
            vnum = int(vk)
            for stem, entry in vdata.items():
                if is_stopword(stem):
                    continue
                rec = records.get(stem)
                if rec is None:
                    rec = {
                        "stem": stem,
                        "count": 0,
                        "score_sum": 0.0,
                        "forms": {},
                        "first_slug": slug,
                        "first_ch": ch_num,
                        "first_v": vnum,
                        "volumes": {},
                        "examples": [],
                    }
                    records[stem] = rec
                rec["count"] += 1
                try:
                    rec["score_sum"] += float(entry.get("score") or 0)
                except (TypeError, ValueError):
                    pass
                for f in entry.get("forms") or []:
                    if not f:
                        continue
                    rec["forms"][f] = rec["forms"].get(f, 0) + 1
                vol = morph.slug_volume(slug)
                rec["volumes"][vol] = rec["volumes"].get(vol, 0) + 1
                # Collect a small pool of representative excerpts (one per stem appearance,
                # capped). We'll prune to the best 3 during fact assembly.
                if len(rec["examples"]) < 12:
                    for m in (entry.get("matches") or [])[:1]:
                        lb = (m.get("lb") or "").strip()
                        x = (m.get("x") or "").strip()
                        if lb and x:
                            rec["examples"].append({"ref": lb, "text": x, "slug": slug, "v": vnum})
                            break

    ranked = list(records.values())
    ranked.sort(key=lambda r: (-r["count"], -r["score_sum"], r["stem"]))
    return ranked


